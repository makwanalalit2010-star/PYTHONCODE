# Write a program to demonstrate polymorphism with a built-in function len() by applying it to a string, list, and dictionary.

name = "python"
numbers = [10,20,30,40,50]
student = {
    "name": "lalit",
    "age" : 20,
    "course" : " msc it"
}

print("length of string:", len(name))
print("length of list:", len(numbers))
print("length of dic:", len(student))